//! DuckDB projections over immutable, committed Parquet files. Cast before
//! UNION ALL: DuckDB's own schema unification cannot reconcile every SQLite mix.
use anyhow::{Context, ensure};
use parquet::{
    basic::Type,
    file::reader::{FileReader, SerializedFileReader},
};
use std::{
    collections::BTreeMap,
    fs::File,
    io::Write,
    path::{Path, PathBuf},
};
use wasmkeep_storage::decode_segment;

fn ident(s: &str) -> String {
    format!("\"{}\"", s.replace('"', "\"\""))
}
fn literal(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}
fn entries(path: &Path) -> anyhow::Result<Vec<PathBuf>> {
    if !path.exists() {
        return Ok(vec![]);
    }
    let mut paths = std::fs::read_dir(path)?
        .map(|e| Ok(e?.path()))
        .collect::<anyhow::Result<Vec<_>>>()?;
    paths.sort();
    Ok(paths)
}
const META: &str = "d._wk_tenant, d._wk_app, d._wk_name, d._wk_seq, d._wk_generation, d._wk_txid, d._wk_committed_at";
struct Part {
    path: PathBuf,
    columns: BTreeMap<String, (String, u8)>,
}

/// Rebuild from file schemas, including visible batches recovered after a crash.
/// No rows are read. Replacing this disposable SQL file is atomic and durable.
pub(super) fn publish(out: &Path) -> anyhow::Result<()> {
    publish_from(out, 0)
}

pub(super) fn publish_from(out: &Path, first: u64) -> anyhow::Result<()> {
    // The views name files by absolute path: resolve it, so every caller
    // writes the same text (on macOS a temporary directory under /var is
    // /private/var once resolved, as the poll resolves it).
    let out = &out.canonicalize()?;
    let mut sql = String::from(
        "-- Generated by wasmkeep feed. Reload after each poll.\nBEGIN TRANSACTION;\n",
    );
    let states = entries(&out.join("_wk_states"))?;
    if !states.is_empty() {
        let states_path = out.join("_wk_states/*.parquet");
        let states_sql = format!(
            "read_parquet({}, union_by_name = true)",
            literal(states_path.to_str().context("non-UTF8 output path")?)
        );
        let mut names = std::collections::BTreeSet::new();
        for class_dir in entries(&out.join("tables"))? {
            let class = decode_segment(
                class_dir
                    .file_name()
                    .and_then(|n| n.to_str())
                    .context("invalid class path")?,
            )
            .context("invalid class encoding")?;
            for table_dir in entries(&class_dir)? {
                let table = decode_segment(
                    table_dir
                        .file_name()
                        .and_then(|n| n.to_str())
                        .context("invalid table path")?,
                )
                .context("invalid table encoding")?;
                let mut parts = vec![];
                let mut columns: BTreeMap<String, (String, u8)> = BTreeMap::new();
                for path in entries(&table_dir)? {
                    if path
                        .file_stem()
                        .and_then(|s| s.to_str())
                        .and_then(|s| s.parse::<u64>().ok())
                        .is_none_or(|seq| seq < first)
                    {
                        continue;
                    }
                    let filename = path.file_name().context("missing filename")?;
                    if path.extension().is_none_or(|e| e != "parquet")
                        || !out.join("_wk_states").join(filename).is_file()
                    {
                        continue;
                    }
                    let reader = SerializedFileReader::new(File::open(&path)?)?;
                    let mut local = BTreeMap::new();
                    for column in reader.metadata().file_metadata().schema_descr().columns() {
                        let name = column.name();
                        let key = name.to_ascii_lowercase();
                        if key.starts_with("_wk_") {
                            continue;
                        }
                        let kind = match column.physical_type() {
                            Type::INT64 => 1,
                            Type::DOUBLE => 2,
                            Type::BYTE_ARRAY if column.logical_type_ref().is_some() => 4,
                            Type::BYTE_ARRAY => 8,
                            other => anyhow::bail!("unsupported feed type {other:?}"),
                        };
                        columns
                            .entry(key.clone())
                            .and_modify(|c| c.1 |= kind)
                            .or_insert((name.into(), kind));
                        local.insert(key, (name.into(), kind));
                    }
                    parts.push(Part {
                        path,
                        columns: local,
                    });
                }
                if parts.is_empty() {
                    continue;
                }
                let view = format!("{class}_{table}");
                let history = format!("{view}_history");
                // Never silently replace another table's view, including a table
                // whose name ends in _history or differs only in ASCII case.
                ensure!(
                    names.insert(view.to_ascii_lowercase())
                        && names.insert(history.to_ascii_lowercase()),
                    "ambiguous DuckDB view name: {view}"
                );
                let mut selects = vec![];
                for part in parts {
                    let mut expressions = vec![];
                    for (key, (name, kinds)) in &columns {
                        let target = match kinds {
                            1 => "BIGINT",
                            2 | 3 => "DOUBLE",
                            8 => "BLOB",
                            _ => "VARCHAR",
                        };
                        let source = match part.columns.get(key) {
                            Some((name, 8)) if target == "VARCHAR" => {
                                format!("'X''' || lower(hex(d.{})) || ''''", ident(name))
                            }
                            Some((name, _)) => format!("d.{}", ident(name)),
                            None => "NULL".into(),
                        };
                        expressions.push(format!("CAST({source} AS {target}) AS {}", ident(name)));
                    }
                    expressions.push(META.into());
                    selects.push(format!(
                        "SELECT {} FROM read_parquet({}) AS d",
                        expressions.join(", "),
                        literal(part.path.to_str().context("non-UTF8 table path")?)
                    ));
                }
                sql.push_str(&format!(
                    "CREATE OR REPLACE VIEW {} AS\n{};\n",
                    ident(&history),
                    selects.join("\nUNION ALL\n")
                ));
                sql.push_str(&format!("CREATE OR REPLACE VIEW {} AS\nSELECT d.* FROM {} AS d JOIN (SELECT * FROM {states_sql} WHERE _wk_class = {} QUALIFY _wk_seq = max(_wk_seq) OVER (PARTITION BY _wk_tenant, _wk_app, _wk_class, _wk_name)) AS s ON d._wk_tenant = s._wk_tenant AND d._wk_app = s._wk_app AND d._wk_name = s._wk_name AND d._wk_seq = s._wk_seq WHERE s._wk_kind <> 'deleted';\n", ident(&view), ident(&history), literal(&class)));
            }
        }
    }
    sql.push_str("COMMIT;\n");
    let path = out.join("views.duckdb.sql");
    if std::fs::read_to_string(&path).ok().as_deref() == Some(&sql) {
        return Ok(());
    }
    let partial = out.join("views.duckdb.sql.partial");
    let mut temporary = File::create(&partial)?;
    temporary.write_all(sql.as_bytes())?;
    temporary.sync_all()?;
    drop(temporary);
    std::fs::rename(partial, path)?;
    File::open(out)?.sync_all()?;
    Ok(())
}
